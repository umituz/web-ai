
import type {
  GeneratedContent,
  PrunaConfig,
  ImageGenerationRequest,
  VideoGenerationRequest,
  ImageToVideoRequest,
  VideoToVideoRequest,
} from '../../content/domain/config/ProviderConfig';
import type { ProviderHealth } from '../../core/types';
import type { CostEstimateRequest, IMediaProvider } from '../base/provider.types';
import { AIError, AIErrorType } from '../../core/errors';
import { generateWithPruna } from './pruna-generate';
export { generateWithPruna } from './pruna-generate';
export type {
  PrunaRequest,
  PrunaProgressStage,
  PrunaCore,
} from './pruna-generate';

/**
 * Pruna media provider: supports text-to-image, text-to-video, and
 * image-to-video generation through the @umituz/pruna-provider client.
 */
export class PrunaProvider implements IMediaProvider {
  readonly id = 'pruna';
  readonly name = 'Pruna AI';
  readonly capabilities = ['image', 'video'] as const;

  constructor(readonly config: PrunaConfig) {}

  async healthCheck(): Promise<ProviderHealth> {
    return this.config.apiKey ? 'healthy' : 'unavailable';
  }

  async estimateCost(_request: CostEstimateRequest): Promise<number> {
    return 1;
  }

  async generateImage(request: ImageGenerationRequest): Promise<GeneratedContent> {
    let finalUrl: string | undefined;
    const model = this.config.models?.textToImage;
    for await (const stage of generateWithPruna(
      { prompt: request.prompt, model, quality: request.quality },
      this.config.apiKey,
    )) {
      if (stage.error) throw stage.error;
      if (stage.result?.url) finalUrl = stage.result.url;
    }
    if (!finalUrl) {
      throw new AIError(AIErrorType.SERVER_ERROR, 'No image generated by Pruna AI');
    }
    return {
      id: Date.now().toString(),
      type: 'image',
      url: finalUrl,
      metadata: { provider: this.id, model: model ?? 'p-image' },
      createdAt: new Date().toISOString(),
    };
  }

  async generateVideo(request: VideoGenerationRequest): Promise<GeneratedContent> {
    let finalUrl: string | undefined;
    const model = this.config.models?.textToVideo;
    for await (const stage of generateWithPruna(
      { prompt: request.prompt, model, duration: request.duration, aspectRatio: request.aspectRatio },
      this.config.apiKey,
    )) {
      if (stage.error) throw stage.error;
      if (stage.result?.url) finalUrl = stage.result.url;
    }
    if (!finalUrl) {
      throw new AIError(AIErrorType.SERVER_ERROR, 'No video generated by Pruna AI');
    }
    return {
      id: Date.now().toString(),
      type: 'video',
      url: finalUrl,
      metadata: { provider: this.id, model: model ?? 'p-video' },
      createdAt: new Date().toISOString(),
    };
  }

  async imageToVideo(request: ImageToVideoRequest): Promise<GeneratedContent> {
    let finalUrl: string | undefined;
    for await (const stage of generateWithPruna(
      { image: request.imageUrl, prompt: request.prompt, duration: request.duration, motion: request.motion },
      this.config.apiKey,
    )) {
      if (stage.error) throw stage.error;
      if (stage.result?.url) finalUrl = stage.result.url;
    }
    if (!finalUrl) {
      throw new AIError(AIErrorType.SERVER_ERROR, 'No video generated from image by Pruna AI');
    }
    return {
      id: Date.now().toString(),
      type: 'video',
      url: finalUrl,
      metadata: { provider: this.id, model: 'p-image-to-video' },
      createdAt: new Date().toISOString(),
    };
  }

  async videoToVideo(_request: VideoToVideoRequest): Promise<GeneratedContent> {
    throw new AIError(AIErrorType.CLIENT_ERROR, 'Pruna AI provider does not support video-to-video conversion');
  }
}

export function createPrunaProvider(config: PrunaConfig): PrunaProvider {
  return new PrunaProvider(config);
}
